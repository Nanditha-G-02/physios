// Training service (pam_trainer) through the gateway: /api/v1/trainer/<route>.
// Thin and explicit: one function per backend route used by PHYSIOS.
import { get, post, qs, request } from './http';

const T = '/trainer';
export const trainer = {
  health: () => get(`${T}/health`, { timeoutMs: 5000 }),
  system: () => get(`${T}/system`),
  envs: (refresh = false) => get(`${T}/envs${refresh ? '?refresh=1' : ''}`, { timeoutMs: 120000 }),
  env: (name: string) => get(`${T}/envs/${encodeURIComponent(name)}`, { timeoutMs: 120000 }),
  datasets: () => get(`${T}/datasets`),
  models: (env: string, dataset?: string) => get(`${T}/models${qs({ env, dataset })}`, { timeoutMs: 120000 }),
  policyFlags: (env: string, policy: string) => get(`${T}/policy-flags${qs({ env, policy })}`, { timeoutMs: 120000 }),
  plan: (config: unknown) => post(`${T}/plan`, { config }, { timeoutMs: 120000 }),
  runs: () => get(`${T}/runs`),
  start: (config: unknown, confirm_token: string) => post(`${T}/runs`, { config, confirm_token }, { timeoutMs: 120000 }),
  run: (id: string) => get(`${T}/runs/${id}`),
  log: (id: string, offset = -1, limit = 65536) => get(`${T}/runs/${id}/log${qs({ offset, limit })}`),
  metrics: (id: string) => get(`${T}/runs/${id}/metrics`),
  diagnostics: (id: string) => get(`${T}/runs/${id}/diagnostics`),
  resources: (id: string) => get(`${T}/runs/${id}/resources`),
  checkpoints: (id: string) => get(`${T}/runs/${id}/checkpoints`),
  runAction: (id: string, action: 'stop' | 'pause' | 'resume', body: unknown = {}) => post(`${T}/runs/${id}/${action}`, body),
  retry: (id: string, mode: string, confirm_token?: string, extra_steps?: number) => post(`${T}/runs/${id}/retry`, { mode, confirm_token, extra_steps }),
  metadata: (id: string, name: string, notes: string) => post(`${T}/runs/${id}/metadata`, { name, notes }),
  exportCkpt: (id: string, step?: number | string) => post(`${T}/runs/${id}/export`, { step }),
  keep: (id: string, step: number | string, keep: boolean) => post(`${T}/runs/${id}/keep`, { step, keep }),
  watch: (id: string, mode: string, settings?: unknown, ack?: boolean) => post(`${T}/runs/${id}/watch`, { mode, settings, ack }),
  queue: () => get(`${T}/queue`),
  enqueue: (config: unknown, confirm_token: string) => post(`${T}/queue`, { config, confirm_token }),
  queueAction: (id: string, action: 'cancel' | 'confirm' | 'move', body: unknown = {}) => post(`${T}/queue/${id}/${action}`, body),
  storage: () => get(`${T}/storage`, { timeoutMs: 60000 }),
  events: (after = 0) => get(`${T}/events${qs({ after })}`),
  compare: (ids: string[]) => get(`${T}/compare${qs({ ids: ids.join(',') })}`),
  evaluations: (run?: string) => get(`${T}/evaluations${qs({ run })}`),
  addTrial: (rec: unknown) => post(`${T}/evaluations`, rec),
  updateTrial: (id: string, rec: unknown) => post(`${T}/evaluations/${id}`, rec),
  deleteTrial: (id: string) => post(`${T}/evaluations/${id}/delete`, {}),
  healthReport: (path: string) => get(`${T}/health-report${qs({ path })}`),
  startHealthReport: (path: string, env?: string, video = true, refresh = false) => post(`${T}/health-report`, { path, env, video, refresh }),
  // optimisation
  optSessions: () => get(`${T}/optimization/sessions`),
  optSession: (id: string) => get(`${T}/optimization/sessions/${id}`),
  optPropose: (request: unknown) => post(`${T}/optimization/propose`, { request }, { timeoutMs: 120000 }),
  optCreate: (request: unknown, confirm_token: string) => post(`${T}/optimization/sessions`, { request, confirm_token }, { timeoutMs: 120000 }),
  optLaunch: (sid: string, tid: string, confirm_token?: string) => post(`${T}/optimization/sessions/${sid}/trials/${tid}/launch`, { confirm_token }, { timeoutMs: 120000 }),
  optStop: (sid: string) => post(`${T}/optimization/sessions/${sid}/stop`, {}),
  optConclude: (sid: string) => post(`${T}/optimization/sessions/${sid}/conclude`, {}),
  // rollouts
  rolloutPrepare: (body: unknown) => post(`${T}/rollouts/prepare`, body, { timeoutMs: 120000 }),
  rolloutStart: (request: unknown, confirm_token: string) => post(`${T}/rollouts`, { request, confirm_token }, { timeoutMs: 120000 }),
  rollouts: () => get(`${T}/rollouts`),
  rollout: (id: string) => get(`${T}/rollouts/${id}`),
  rolloutLog: (id: string) => get(`${T}/rollouts/${id}/log`),
  rolloutCommand: (id: string, command: string) => post(`${T}/rollouts/${id}/command`, { command }, { timeoutMs: 10000 }),
  rolloutHeartbeat: (id: string) => post(`${T}/rollouts/${id}/heartbeat`, {}, { timeoutMs: 4000 }),
  rolloutLimits: (dataset_id: string, joints: unknown[]) => post(`${T}/rollouts/limits`, { dataset_id, limits: { joints } }),
  // robots
  robots: () => get(`${T}/robots`),
  robot: (id: string) => get(`${T}/robots/${id}`),
  robotCreate: (body: unknown) => post(`${T}/robots`, body),
  robotUpload: (id: string, data: Blob, kind: 'zip' | 'file', path = '') =>
    request('POST', `${T}/robots/${id}/upload${qs({ kind: kind === 'zip' ? 'zip' : undefined, path: kind === 'file' ? path : undefined })}`, undefined, { raw: data, timeoutMs: 300000 }),
  robotAction: (id: string, action: 'update' | 'replace' | 'validate' | 'register' | 'connect' | 'delete', body: unknown = {}) => post(`${T}/robots/${id}/${action}`, body, { timeoutMs: 120000 }),
  robotDefaultConfig: (id: string) => get(`${T}/robots/${id}/config`),
  robotSaveConfig: (id: string, config: unknown) => post(`${T}/robots/${id}/config`, { config }),
  robotServerConfig: (id: string) => get(`${T}/robots/${id}/server-config`),
  robotVerifyRos: (id: string, evidence: unknown) => post(`${T}/robots/${id}/verify/ros`, { evidence }),
  robotHwAuthorize: (id: string, joint: string, confirmations: unknown, confirm_name: string) => post(`${T}/robots/${id}/verify/hardware/authorize`, { joint, confirmations, confirm_name }),
  robotHwResult: (id: string, token: string, result: unknown) => post(`${T}/robots/${id}/verify/hardware/result`, { token, result }),
  robotVerifyData: (id: string, policy?: string, dataset_id?: string) => post(`${T}/robots/${id}/verify/data`, { policy, dataset_id }),
};

export const ACTIVE_RUN = ['starting', 'copying', 'converting', 'training', 'paused', 'stopping'];
